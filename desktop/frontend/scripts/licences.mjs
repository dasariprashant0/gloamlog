// Writes ../../../THIRD_PARTY_LICENSES.md for the Go + Wails app (Settings > About > Third-party licences opens it; build.sh
// copies it into the app bundle). Run from desktop/frontend:  npm run licences   (needs node_modules and Go; no network)
// npm: every production package in package-lock.json (dev tools are not shipped). Go: every module the app's binary links
// (`go list -deps` of desktop/), with the licence files in the module cache.
import {execFileSync} from 'node:child_process'
import {existsSync} from 'node:fs'
import {readdir, readFile, writeFile} from 'node:fs/promises'
import {dirname, join, resolve} from 'node:path'
import {fileURLToPath} from 'node:url'

const front = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const desktop = resolve(front, '..')
const outFile = resolve(desktop, '../THIRD_PARTY_LICENSES.md')

async function licenceText(dir) {
  if (!dir || !existsSync(dir)) return ''
  const names = (await readdir(dir)).filter((f) => /^(licen[sc]e|copying|notice)/i.test(f)).sort()
  let text = ''
  for (const f of names) text += (text ? '\n\n' : '') + (await readFile(join(dir, f), 'utf8')).trim()
  return text
}

// npm: production packages from the lockfile ("node_modules/a/node_modules/b" keeps its own copy).
const lock = JSON.parse(await readFile(join(front, 'package-lock.json'), 'utf8'))
const npm = []
for (const [path, meta] of Object.entries(lock.packages || {})) {
  if (!path || meta.dev || meta.link) continue
  const dir = join(front, path)
  let pkg = {}
  try { pkg = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8')) } catch { continue } // optional, not installed here
  const own = (pkg.name || '').startsWith('@personal/') // the owner's own design system: not third-party
  const license = own ? "the owner's own" : typeof pkg.license === 'string' ? pkg.license : pkg.license?.type || meta.license || 'UNKNOWN'
  npm.push({name: pkg.name || path.split('node_modules/').pop(), version: pkg.version || meta.version, license, text: await licenceText(dir)})
}

// Go: modules the desktop binary links.
const goList = execFileSync('go', ['list', '-deps', '-f', '{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}', '.'], {cwd: desktop, encoding: 'utf8'})
const goMods = new Map()
for (const line of goList.split('\n').filter(Boolean)) {
  const [path, version, dir] = line.split('\t')
  if (!goMods.has(path)) goMods.set(path, {name: path, version, license: '', text: await licenceText(dir)})
}
const go = [...goMods.values()]
for (const m of go) m.license = /MIT License|Permission is hereby granted, free of charge/.test(m.text) ? 'MIT'
  : /Apache License/.test(m.text) ? 'Apache-2.0' : /Redistribution and use in source and binary forms/.test(m.text) ? 'BSD' : m.text ? 'see text' : 'UNKNOWN'

const byName = (a, b) => a.name.localeCompare(b.name)
npm.sort(byName); go.sort(byName)
const all = [...npm, ...go]
const groups = new Map()
for (const p of all) {
  const key = (p.text || `(no licence file; ${p.license})`).replace(/\s+/g, ' ')
  if (!groups.has(key)) groups.set(key, {text: p.text, pkgs: []})
  groups.get(key).pkgs.push(`${p.name} ${p.version}`)
}
const row = (p) => `| ${p.name} | ${p.version} | ${p.license} |`
const md = `# Third-party licences

Gloamlog itself is MIT (see \`LICENSE\`). The app is built from Go (\`desktop/\`, with Wails) and a React interface
(\`desktop/frontend/\`) that includes the Milkdown editor. This file lists every npm package the interface ships (production
dependencies) and every Go module the app links, with their licence texts. It is generated by \`npm run licences\` in
\`desktop/frontend/\`; do not edit it by hand.

## npm packages (${npm.length})

| Package | Version | Licence |
|---|---|---|
${npm.map(row).join('\n')}

## Go modules (${go.length})

| Module | Version | Licence |
|---|---|---|
${go.map(row).join('\n')}

## Licence texts

Each text is copied verbatim from the package or module; those with an identical text share one entry.

${[...groups.values()].sort((a, b) => a.pkgs[0].localeCompare(b.pkgs[0]))
  .map((g) => `### ${g.pkgs.join(', ')}\n\n${g.text ? '```text\n' + g.text + '\n```' : '(no licence file shipped; the licence is the one listed in the tables above)'}\n`).join('\n')}`

await writeFile(outFile, md)
const unknown = all.filter((p) => p.license === 'UNKNOWN')
console.log(`wrote ${outFile}: ${npm.length} npm packages, ${go.length} Go modules, ${groups.size} distinct texts`)
for (const p of unknown) console.log(`  UNKNOWN ${p.name}@${p.version}`)
